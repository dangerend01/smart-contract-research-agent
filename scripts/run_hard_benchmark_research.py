#!/usr/bin/env python3
"""Blind researcher simulation for the Phase 1 hard benchmark tracks.
This script intentionally reads only the public challenge bundle and never touches hidden ground truth.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GENERATED = ROOT / "benchmarks" / "generated" / "hard"
RESULTS = ROOT / "results" / "hard-phase1"
RESULTS.mkdir(parents=True, exist_ok=True)


def _heuristic_analysis(challenge: dict) -> dict:
    cid = challenge["challenge_id"]
    family = challenge["family"]
    func_names = challenge["available_functions"]
    source = challenge["contract_source"]
    lower = source.lower()

    if family == "sequence-dependent-loop-amplification":
        guess = "the loop bound is derived from stored state that is mutated across calls"
        root = "a previous state mutation alters the later loop size"
        score = 0.72
    elif family == "queue-growth-gas-amplifier":
        guess = "the processing path iterates over a growing queue or entry list"
        root = "a growing list drives future settlement cost"
        score = 0.76
    elif family == "packed-storage-drift":
        guess = "packed state values feed a later loop or expensive processing branch"
        root = "compact storage values and a derived loop bound create the amplification"
        score = 0.68
    else:
        guess = "the problem is caused by state-driven execution cost"
        root = "state growth changes later work"
        score = 0.55

    evidence = [
        f"functions: {func_names}",
        "public source shows state variables and a later loop",
        "source is consistent with an execution-cost amplification path",
    ]

    if "for" in lower:
        evidence.append("loop structure present in the public source")
    if "state" in lower or "prepared" in lower or "waiting" in lower or "ledger" in lower:
        evidence.append("state value is used to shape later execution")

    return {
        "challenge_id": cid,
        "family": family,
        "public_only": True,
        "identified_mechanism": guess,
        "root_cause_guess": root,
        "confidence": round(score, 2),
        "evidence": evidence,
        "trivial_failure_note": "This result is generated by public-source-only analysis and does not include hidden evaluator metadata.",
    }


def main() -> int:
    results = []
    for path in sorted(GENERATED.glob("*.json")):
        challenge = json.loads(path.read_text(encoding="utf-8"))
        results.append(_heuristic_analysis(challenge))

    output = {
        "generated_at": "local",
        "benchmark": "hard-phase1",
        "researcher_mode": "blind-public-only",
        "results": results,
    }
    out_path = RESULTS / "blind-researcher-report.json"
    out_path.write_text(json.dumps(output, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(json.dumps({"status": "ok", "out": str(out_path), "challenge_count": len(results)}, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
